test('image crop geometry keeps ratios and stays inside the image', () => {
 assert.deepEqual(centeredCrop(1920, 1080, 1), { x: 420, y: 0, width: 1080, height: 1080 });
 assert.deepEqual(centeredCrop(1000, 1000, 16 / 9), { x: 0, y: 218, width: 1000, height: 563 });
 assert.deepEqual(centeredCrop(300, 200, null), { x: 0, y: 0, width: 300, height: 200 });
 assert.deepEqual(validateCrop({ x: '10', y: '0', width: '90', height: '50' }, 100, 50), { x: 10, y: 0, width: 90, height: 50 });
 for (const bad of [{ x: -1, y: 0, width: 5, height: 5 }, { x: 0, y: 0, width: 0, height: 5 }, { x: 96, y: 0, width: 5, height: 5 }, { x: 1.5, y: 0, width: 5, height: 5 }]) assert.throws(() => validateCrop(bad, 100, 100));
 assert.deepEqual(rectFromDrag({ x: 80, y: 80 }, { x: 20, y: 30 }, null, 100, 100), { x: 20, y: 30, width: 60, height: 50 });
 assert.deepEqual(rectFromDrag({ x: 10, y: 10 }, { x: 200, y: 40 }, 1, 100, 100), { x: 10, y: 10, width: 90, height: 90 });
 const dragged = rectFromDrag({ x: 50, y: 50 }, { x: 0, y: 0 }, 16 / 9, 100, 100);
 assert.ok(Math.abs(dragged.width / dragged.height - 16 / 9) < 0.05 && dragged.x >= 0 && dragged.y >= 0);
 assert.equal(ratioValue('free'), null); assert.throws(() => ratioValue('2:7'));
});
test('chart data parsing detects headers, series, and invalid rows', () => {
 const data = parseChartData('Month, A, B\nJan, 1, -2\nFeb, 3.5, 4');
 assert.deepEqual(data, { labels: ['Jan', 'Feb'], series: [{ name: 'A', values: [1, 3.5] }, { name: 'B', values: [-2, 4] }] });
 assert.deepEqual(parseChartData('x, 5\ny, "1,200"').series, [{ name: 'Value', values: [5, 1200] }]);
 assert.throws(() => parseChartData('a, b\nc'), /Row 2/); assert.throws(() => parseChartData('Label, V\na, ten'), /not a number/);
 assert.throws(() => parseChartData('only labels')); assert.throws(() => parseChartData('a, "1'), /not closed/); assert.throws(() => parseChartData('a, "1"x'), /after a closing quote/); assert.throws(() => parseChartData('a,1,2,3,4,5,6'), /at most 5/);
 assert.deepEqual(niceScale(-3, 47).ticks, [-10, 0, 10, 20, 30, 40, 50]); assert.deepEqual(niceScale(0, 0).ticks.slice(0, 2), [0, 0.2]);
 const bars = layoutChart(data, 'bar');
 assert.equal(bars.shapes.filter(s => s.kind === 'rect').length, 4);
 const negative = bars.shapes.find(s => s.title === 'B · Jan: -2'), zero = bars.shapes.find(s => s.kind === 'line' && s.stroke === '#5b635d');
 assert.ok(Math.abs(negative.y - zero.y1) < 1e-9, 'negative bars hang from the zero line');
 assert.equal(layoutChart(data, 'line').shapes.filter(s => s.kind === 'polyline').length, 2);
 const pie = layoutChart(parseChartData('a,1\nb,3\nc,0'), 'pie');
 assert.equal(pie.shapes.length, 2); assert.equal(pie.legend[1].name, 'b · 75.0%');
 assert.match(layoutChart(parseChartData('only,5'), 'pie').shapes[0].d, / a /, 'a single 100% slice is drawn as a full circle');
 assert.throws(() => layoutChart(data, 'pie'), /one value column/); assert.throws(() => layoutChart(parseChartData('a,-1\nb,2'), 'pie'), /negative/);
 assert.throws(() => layoutChart(parseChartData('a,0'), 'pie'), /more than zero/);
});
test('audio trimming converts times, ranges, fades, and 16-bit WAV output', () => {
 assert.equal(parseTime('75.5', 'x'), 75.5); assert.equal(parseTime('1:15.5', 'x'), 75.5); assert.equal(parseTime('1:02:03', 'x'), 3723);
 for (const bad of ['', '-1', '1:75', 'abc', '1::2']) assert.throws(() => parseTime(bad, 'Start'));
 assert.equal(formatTime(75.5), '1:15.50');
 assert.deepEqual(trimRange(1, 2.5, 10, 8000, 1), { first: 8000, frames: 12000 });
 assert.throws(() => trimRange(2, 1, 10, 8000)); assert.throws(() => trimRange(0, 11, 10, 8000), /beyond/);
 assert.throws(() => trimRange(0, 1800, 1800, 48000, 2), /100 MiB/);
 assert.deepEqual([...applyFades(new Float32Array([1, 1, 1, 1]), 2, 1, 1)], [0, 0.5, 0.5, 0]);
 const wav = new DataView(encodeWAV([new Float32Array([0, 1, -1]), new Float32Array([0.5, 2, -2])], 8000));
 const text = (o, n) => String.fromCharCode(...Array.from({ length: n }, (_, i) => wav.getUint8(o + i)));
 assert.equal(text(0, 4), 'RIFF'); assert.equal(text(8, 4), 'WAVE'); assert.equal(wav.getUint16(22, true), 2); assert.equal(wav.getUint32(24, true), 8000); assert.equal(wav.getUint32(40, true), 12);
 assert.deepEqual([0, 1, 2, 3, 4, 5].map(i => wav.getInt16(44 + i * 2, true)), [0, 16384, 32767, 32767, -32768, -32768]);
 assert.deepEqual(peaks(new Float32Array([0, 0.5, -0.25, 1]), 2), [[0, 0.5], [-0.25, 1]]);
});
test('flashcards follow Leitner scheduling and validate backups', () => {
 const card = validate({ title: ' Capital of France? ', back: 'Paris', deck: '', box: 1, due: '2026-09-26' });
 assert.deepEqual(card, { title: 'Capital of France?', back: 'Paris', deck: 'General', box: 1, due: '2026-09-26' });
 assert.deepEqual(review(card, true, '2026-09-26'), { ...card, box: 2, due: '2026-09-28' });
 assert.deepEqual(review({ ...card, box: 5 }, true, '2026-12-31'), { ...card, box: 5, due: '2027-01-16' });
 assert.deepEqual(review({ ...card, box: 4 }, false, '2026-09-26'), { ...card, box: 1, due: '2026-09-26' });
 assert.equal(addDays('2028-02-28', 1), '2028-02-29');
 const cards = [{ ...card, id: 'a', due: '2026-09-27' }, { ...card, id: 'b', deck: 'Spanish', due: '2026-09-20' }, { ...card, id: 'c', due: '2026-09-26', box: 3 }];
 assert.deepEqual(dueCards(cards, 'all', '2026-09-26').map(c => c.id), ['b', 'c']);
 assert.deepEqual(dueCards(cards, 'General', '2026-09-26').map(c => c.id), ['c']);
 assert.equal(deckSummary(cards, '2026-09-26'), '3 cards · 2 due today');
 assert.equal(deckSummary([cards[0]], '2026-09-26'), '1 card · 0 due today · next review 2026-09-27');
 for (const bad of [{ box: 0 }, { box: 6 }, { box: 2.5 }, { due: '2026-02-30' }, { back: '' }, { title: 'x'.repeat(501) }]) assert.throws(() => validate({ ...card, ...bad }));
 const config = { id: 'flashcards', validate };
 assert.equal(validateBackup({ version: 1, tool: 'flashcards', records: [{ ...card, id: 'x' }] }, config).records[0].box, 1);
 assert.throws(() => validateBackup({ version: 1, tool: 'notes', records: [] }, config));
});
